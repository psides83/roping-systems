begin;
do $$
declare p uuid; d uuid; t uuid; other uuid; f uuid; stamp timestamptz;
begin
  insert into public.producers(name,slug) values ('Content date regression', 'content-date-'||gen_random_uuid()::text) returning id into p;
  insert into public.divisions(producer_id,name) values(p,'Test division') returning id into d;
  insert into public.roping_templates(producer_id,division_id,name) values(p,d,'Test template') returning id into t;
  insert into public.roping_templates(producer_id,division_id,name) values(p,d,'Other template') returning id into other;
  select content_updated_at into stamp from public.roping_templates where id=t;
  if stamp is null then raise exception 'New templates need a content date'; end if;
  update public.roping_templates set sort_order=sort_order+1 where id=t;
  if (select content_updated_at from public.roping_templates where id=t) is distinct from stamp then raise exception 'Reorder changed content date'; end if;
  update public.roping_templates set name=name where id=t;
  if (select content_updated_at from public.roping_templates where id=t) is distinct from stamp then raise exception 'No-op save changed content date'; end if;
  update public.roping_templates set content_updated_at=null where id=t;
  update public.roping_templates set sort_order=sort_order+1 where id=t;
  if (select content_updated_at from public.roping_templates where id=t) is not null then raise exception 'Reorder invented historical date'; end if;
  update public.roping_templates set description='Changed content' where id=t;
  if (select content_updated_at from public.roping_templates where id=t) is null then raise exception 'Template edit did not set date'; end if;
  update public.roping_templates set content_updated_at='2000-01-01' where id=t;
  insert into public.roping_template_fees(producer_id,roping_template_id,title,amount_cents,scope) values(p,t,'Entry fee',1000,'entry') returning id into f;
  if (select content_updated_at from public.roping_templates where id=t)<='2000-01-01'::timestamptz then raise exception 'Fee insert did not advance date'; end if;
  select content_updated_at into stamp from public.roping_templates where id=t;
  update public.roping_template_fees set sort_order=sort_order+1 where id=f;
  update public.roping_template_fees set amount_cents=amount_cents where id=f;
  if (select content_updated_at from public.roping_templates where id=t) is distinct from stamp then raise exception 'Fee reorder/no-op changed date'; end if;
  update public.roping_templates set content_updated_at='2000-01-01' where id=t;
  update public.roping_template_fees set amount_cents=2000 where id=f;
  if (select content_updated_at from public.roping_templates where id=t)<='2000-01-01'::timestamptz then raise exception 'Fee edit did not advance date'; end if;
  update public.roping_templates set content_updated_at='2000-01-01' where id in(t,other);
  update public.roping_template_fees set roping_template_id=other where id=f;
  if exists(select 1 from public.roping_templates where id in(t,other) and content_updated_at<='2000-01-01'::timestamptz) then raise exception 'Moving fee did not update both templates'; end if;
  update public.roping_templates set content_updated_at='2000-01-01' where id=other;
  delete from public.roping_template_fees where id=f;
  if (select content_updated_at from public.roping_templates where id=other)<='2000-01-01'::timestamptz then raise exception 'Fee deletion did not advance date'; end if;
  insert into public.roping_template_fees(producer_id,roping_template_id,title,amount_cents,scope) values(p,t,'Cascade fee',1000,'entry');
  delete from public.roping_templates where id=t;
  if exists(select 1 from public.roping_template_fees where roping_template_id=t) then raise exception 'Template cascade left fees behind'; end if;
end;
$$;
select 'Template content date checks passed' as result;
rollback;
